# Bend text helpers for the implementation

def rot(v, m):
    if m == 0:
        return v
    return f"U32.or(U32.shln({v},{m}n),U32.shrn({v},{32 - m}n))"


def xor(a, b):
    return f"U32.xor({a},{b})"


def neg(v, n):
    return f"U32.not({v})" if n else v


def chi_k(k, a, b, c):
    nx, op, ny, nz = CHI[k]
    return f"U32.xor({neg(a, nx)},U32.{op}({neg(b, ny)},{neg(c, nz)}))"


def round_body(ins, rce, rco, tag, indent="      "):
    L = []
    for x in range(5):
        for p, s in ((0, "e"), (1, "o")):
            L.append(f"+c{x}{s}{tag} = " + xor(ins[x][p], xor(ins[x + 5][p], xor(ins[x + 10][p], xor(ins[x + 15][p], ins[x + 20][p])))))
    for x in range(5):
        cp, cn = (x - 1) % 5, (x + 1) % 5
        L.append(f"+d{x}e{tag} = " + xor(f"c{cp}e{tag}", rot(f"c{cn}o{tag}", 1)))
        L.append(f"+d{x}o{tag} = " + xor(f"c{cp}o{tag}", f"c{cn}e{tag}"))
    outs = [None] * 25
    for row in range(5):
        for dest in range(5 * row, 5 * row + 5):
            src, r = B[dest]
            x = src % 5
            ae, ao = xor(ins[src][0], f"d{x}e{tag}"), xor(ins[src][1], f"d{x}o{tag}")
            if r % 2 == 0:
                be, bo = rot(ae, r // 2), rot(ao, r // 2)
            else:
                be, bo = rot(ao, r // 2 + 1), rot(ae, r // 2)
            L.append(f"+b{dest}e{tag} = {be}")
            L.append(f"+b{dest}o{tag} = {bo}")
        for dest in range(5 * row, 5 * row + 5):
            _, i1, i2 = row3(dest)
            for s in "eo":
                v = chi_k(dest, f"b{dest}{s}{tag}", f"b{i1}{s}{tag}", f"b{i2}{s}{tag}")
                if dest == 0:
                    v = xor(v, rce if s == "e" else rco)
                L.append(f"+q{dest}{s}{tag} = {v}")
            outs[dest] = (f"q{dest}e{tag}", f"q{dest}o{tag}")
    return [indent + l for l in L], outs


def plus_fields(p=""):
    return ",".join(f"+{p}e{k},+{p}o{k}" for k in range(25))


def st_fields(p=""):
    return ",".join(f"{p}e{k},{p}o{k}" for k in range(25))



