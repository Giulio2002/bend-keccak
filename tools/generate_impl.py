PAD = """# Little-endian Keccak pad10*1, domain suffix 0x01.
def partial(w: U32, delta: Nat) -> U32:
  match delta:
    case 0n: 1
    case 1n: U32.or(U32.and(w,255),256)
    case 2n: U32.or(U32.and(w,65535),65536)
    case 3n: U32.or(U32.and(w,16777215),16777216)
    case _: w

def pad_choose(c: Cmp, w: U32, delta: Nat) -> U32:
  match c:
    case GT{}: 0
    case EQ{}: 1
    case LT{}: partial(w,delta)

def pad_word(w: U32, +pos: Nat, +remain: Nat) -> U32:
  pad_choose(Nat.cmp(pos,remain),w,Nat.sub(remain,pos))
"""

TAIL = """def digest(s: T.State) -> Array<U32>:
  match s:
    case T.S{T.W{l0,h0},T.W{l1,h1},T.W{l2,h2},T.W{l3,h3},a4,a5,a6,a7,a8,a9,a10,a11,a12,a13,a14,a15,a16,a17,a18,a19,a20,a21,a22,a23,a24}:
      a = Array.new(U32,3n,0)
      a = Array.set(U32,a,0,l0)
      a = Array.set(U32,a,1,h0)
      a = Array.set(U32,a,2,l1)
      a = Array.set(U32,a,3,h1)
      a = Array.set(U32,a,4,l2)
      a = Array.set(U32,a,5,h2)
      a = Array.set(U32,a,6,l3)
      a = Array.set(U32,a,7,h3)
      a

def checked(+round_count: Nat,valid: Bool, a: Array<U32>, length: Nat) -> Maybe<&1,Array<U32>>:
  match valid:
    case False{}: None{}
    case True{}: Some{digest(L.squeeze(unchecked(round_count,a,length)))}

def sized(+round_count: Nat,+length: Nat, pair: Array<U32> & U32) -> Maybe<&1,Array<U32>>:
  (a,capacity) = pair
  checked(round_count,Nat.is_le(length,Nat.mul(4n,U32.to_nat(capacity))),a,length)

def keccak256_rounds(+round_count: Nat,a: Array<U32>, length: Nat) -> Maybe<&1,Array<U32>>:
  sized(round_count,length,Array.size(U32,a))


def keccak256(a: Array<U32>, length: Nat) -> Maybe<&1,Array<U32>>:
  keccak256_rounds(24n,a,length)
"""


def gen_keccak():
    o = [HEADER, "#",
         "# The Keccak-256 sponge over packed little-endian words: each block's 34",
         "# words are read in one unrolled chain, XORed into the interleaved state",
         "# (src/lane.bend) and permuted (src/permutation.bend); the last block is",
         "# padded word by word.",
         "import Base",
         "import ./types.bend as T",
         "import ./lane.bend as L",
         "import ./permutation.bend as P", ""]
    ws = lambda n: "".join(f", w{i}: U32" for i in range(n))
    wa = lambda n: "".join(f",w{i}" for i in range(n))
    o.append(f"def read33(+round_count: Nat,+index: U32, s: T.St{ws(33)}, pair: Array<U32> & U32) -> Array<U32> & T.St:")
    o.append("  (a,w33) = pair")
    o.append(f"  (a,P.steps(round_count,0n,L.mix(s{wa(34)})))")
    o.append("")
    for k in range(32, -1, -1):
        o.append(f"def read{k}(+round_count: Nat,+index: U32, s: T.St{ws(k)}, pair: Array<U32> & U32) -> Array<U32> & T.St:")
        o.append(f"  (a,w{k}) = pair")
        o.append(f"  read{k + 1}(round_count,index,s{wa(k + 1)},Array.get(U32,a,U32.add(index,{k + 1})))")
        o.append("")
    o.append("def absorb(+round_count: Nat,a: Array<U32>, +index: U32, s: T.St) -> Array<U32> & T.St:")
    o.append("  read0(round_count,index,s,Array.get(U32,a,index))")
    o.append("")
    o.append(PAD)
    padded = ",".join(f"pad_word(w{i},{4 * i}n,remain)" for i in range(33)) + ",U32.or(pad_word(w33,132n,remain),2147483648)"
    o.append(f"def pad33(+round_count: Nat,+remain: Nat, +index: U32, s: T.St{ws(33)}, pair: Array<U32> & U32) -> T.St:")
    o.append("  (a,w33) = pair")
    o.append(f"  P.steps(round_count,0n,L.mix(s,{padded}))")
    o.append("")
    for k in range(32, -1, -1):
        o.append(f"def pad{k}(+round_count: Nat,+remain: Nat, +index: U32, s: T.St{ws(k)}, pair: Array<U32> & U32) -> T.St:")
        o.append(f"  (a,w{k}) = pair")
        o.append(f"  pad{k + 1}(round_count,remain,index,s{wa(k + 1)},Array.get(U32,a,U32.add(index,{k + 1})))")
        o.append("")
    o += ["def finish(+round_count: Nat,a: Array<U32>, +index: U32, remain: Nat, s: T.St) -> T.St:",
          "  pad0(round_count,remain,index,s,Array.get(U32,a,index))", "",
          "def blocks(+round_count: Nat,n: Nat, +index: U32, remain: Nat, pair: Array<U32> & T.St) -> T.St:",
          "  match n pair:",
          "    case 0n Tuple{a,s}: finish(round_count,a,index,remain,s)",
          "    case 1n+p Tuple{a,s}: blocks(round_count,p,U32.add(index,34),remain,absorb(round_count,a,index,s))", "",
          "def unchecked(+round_count: Nat,a: Array<U32>, +length: Nat) -> T.St:",
          "  blocks(round_count,Nat.div(length,136n),0,Nat.mod(length,136n),(a,P.initial()))", "",
          TAIL]
    return "\n".join(o)


