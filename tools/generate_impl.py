def row3(k):
    y = k - k % 5
    return k, y + (k - y + 1) % 5, y + (k - y + 2) % 5


def split(v):
    e = o = 0
    for k in range(32):
        e |= ((v >> (2 * k)) & 1) << k
        o |= ((v >> (2 * k + 1)) & 1) << k
    return e, o


