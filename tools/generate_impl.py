# Symbolic Bool / Word evaluation, mirroring Base.

T, F = ("c", True), ("c", False)


def var(n):
    return ("v", n)


def bnot(a):
    if a[0] == "c":
        return ("c", not a[1])
    return ("not", a)


def bxor(a, b):
    if a == F:
        return b
    if a == T:
        return bnot(b)
    return ("xor", a, b)


def band(a, b):
    if a == F:
        return F
    if a == T:
        return b
    return ("and", a, b)


def bor(a, b):
    if a == F:
        return b
    if a == T:
        return T
    return ("or", a, b)


def lit(n):
    return [("c", bool((n >> i) & 1)) for i in range(32)]


def wvar(p, off=0):
    return [var(f"{p}{off + i}") for i in range(32)]


def w_not(a):
    return [bnot(x) for x in a]


def w_xor(a, b):
    return [bxor(x, y) for x, y in zip(a, b)]


def w_and(a, b):
    return [band(x, y) for x, y in zip(a, b)]


def w_or(a, b):
    return [bor(x, y) for x, y in zip(a, b)]


def w_shln(a, n):
    return [F] * n + a[: 32 - n] if n else a


def w_shrn(a, n):
    return a[n:] + [F] * n if n else a


def w_rot(a, m):
    return a if m == 0 else w_or(w_shln(a, m), w_shrn(a, 32 - m))


def bshow(e):
    t = e[0]
    if t == "c":
        return "True{}" if e[1] else "False{}"
    if t == "v":
        return e[1]
    if t == "not":
        return f"Bool.not({bshow(e[1])})"
    return f"Bool.{t}({bshow(e[1])},{bshow(e[2])})"


def bvars(e, acc):
    if e[0] == "v":
        if e[1] not in acc:
            acc.append(e[1])
    elif e[0] != "c":
        for x in e[1:]:
            bvars(x, acc)
    return acc


def bsubst(e, m):
    if e[0] == "v":
        return m[e[1]]
    if e[0] == "c":
        return e
    return (e[0],) + tuple(bsubst(x, m) for x in e[1:])


def beval(e, env):
    t = e[0]
    if t == "c":
        return e[1]
    if t == "v":
        return env[e[1]]
    if t == "not":
        return not beval(e[1], env)
    a, b = beval(e[1], env), beval(e[2], env)
    return {"xor": a != b, "and": a and b, "or": a or b}[t]


class Bools:
    """Generated Bool lemmas, one per distinct (lhs, rhs) shape."""

    def __init__(self, prefix):
        self.prefix = prefix
        self.lemmas = {}
        self.out = []

    def prove(self, lhs, rhs):
        """A proof term of {lhs == rhs : Bool}."""
        if lhs == rhs:
            return "{==}"
        names = bvars(rhs, bvars(lhs, []))
        canon = {n: var(f"x{i}") for i, n in enumerate(names)}
        cl, cr = bsubst(lhs, canon), bsubst(rhs, canon)
        key = (cl, cr)
        if key not in self.lemmas:
            k = len(names)
            for vals in itertools.product([False, True], repeat=k):
                env = {f"x{i}": v for i, v in enumerate(vals)}
                if beval(cl, env) != beval(cr, env):
                    raise ValueError(f"false bit identity {bshow(cl)} == {bshow(cr)}")
            name = f"{self.prefix}{len(self.lemmas)}"
            self.lemmas[key] = name
            params = [f"x{i}" for i in range(k)]
            L = [f"law {name}:"]
            L += [f"  for {p}: Bool" for p in params]
            L.append(f"  {{{bshow(cl)} == {bshow(cr)} : Bool}}")
            L.append("")
            L.append(f"def {name}({','.join(params)}):")
            if k == 0:
                L.append("  {==}")
            else:
                L.append(f"  match {' '.join(params)}:")
                for vals in itertools.product(["False{}", "True{}"], repeat=k):
                    L.append(f"    case {' '.join(vals)}: {{==}}")
            L.append("")
            self.out += L
        return f"{self.lemmas[key]}({','.join(names)})"

    def ext(self, x, y, lhs, rhs):
        """ext32(x, y, ...) proving {x == y : U32} from their symbolic bits."""
        hs = [self.prove(a, b) for a, b in zip(lhs, rhs)]
        return f"X.ext32({x},{y},{','.join(hs)})"


def upat(p, off=0):
    s = "WNil{}"
    for i in reversed(range(32)):
        s = f"WCon{{{p}{off + i},{s}}}"
    return "U32{" + s + "}"


def uword(bits):
    s = "WNil{}"
    for b in reversed(bits):
        s = f"WCon{{{b},{s}}}"
    return "U32{" + s + "}"


def lpat(p):
    """A lane blasted into bits p0..p63 (lo is p0..p31)."""
    return f"T.W{{{upat(p, 0)},{upat(p, 32)}}}"


def lwords(p):
    return wvar(p, 0), wvar(p, 32)


# Mirrors of the lane-level functions -----------------------------------------

def ie_w(lo, hi):
    return [lo[2 * k] for k in range(16)] + [hi[2 * k] for k in range(16)]


def io_w(lo, hi):
    return [lo[2 * k + 1] for k in range(16)] + [hi[2 * k + 1] for k in range(16)]


def spec_rol(lo, hi, r):
    """spec/permutation.bend rotate."""
    if r == 0:
        return lo, hi
    if r < 32:
        return (w_or(w_shln(lo, r), w_shrn(hi, 32 - r)), w_or(w_shln(hi, r), w_shrn(lo, 32 - r)))
    q = r - 32
    return (w_or(w_shln(hi, q), w_shrn(lo, 32 - q)), w_or(w_shln(lo, q), w_shrn(hi, 32 - q)))


def impl_rot(e, o, r):
    if r % 2 == 0:
        return w_rot(e, r // 2), w_rot(o, r // 2)
    return w_rot(o, r // 2 + 1), w_rot(e, r // 2)


def spec_chi(a, b, c):
    return w_xor(a, w_and(w_xor(b, lit(0xFFFFFFFF)), c))


def impl_chi(k, a, b, c):
    nx, op, ny, nz = CHI[k]
    f = w_or if op == "or" else w_and
    return w_xor(w_not(a) if nx else a, f(w_not(b) if ny else b, w_not(c) if nz else c))


def mx(w, m):
    return w_not(w) if m else w


