STAGES = [(1, 0x22222222), (2, 0x0C0C0C0C), (4, 0x00F000F0), (8, 0x0000FF00)]


def stage_w(x, k, m):
    t = w_and(lit(m), w_xor(x, w_shrn(x, k)))
    return w_xor(w_xor(x, t), w_shln(t, k))


def stage_perm(k, m):
    """The bit permutation computed by a stage: out[i] = in[perm[i]]."""
    perm = []
    for i in range(32):
        hits = [j for j in range(32) if (stage_int(1 << j, k, m) >> i) & 1]
        assert len(hits) == 1
        perm.append(hits[0])
    return perm


def stage_int(x, k, m):
    t = (x ^ (x >> k)) & m
    return (x ^ t ^ (t << k)) & 0xFFFFFFFF


def ub_entry(b, k):
    v = 0
    for j in range(4):
        v |= ((b >> (2 * j)) & 1) << (4 * k + j)
        v |= ((b >> (2 * j + 1)) & 1) << (16 + 4 * k + j)
    return v


BYTE_SEL = ["U32.and(255,x)", "U32.and(255,U32.shrn(x,8n))", "U32.and(255,U32.shrn(x,16n))", "U32.shrn(x,24n)"]


def compose(*perms):
    """perm of applying perms[0] first."""
    idx = list(range(32))
    for p in perms:
        idx = [idx[p[i]] for i in range(32)]
    return idx



def gen_lane():
    o = [HEADER, "#",
         "# Conversions between little-endian words and interleaved lanes. unz moves",
         "# a word's even bits to its low half and its odd bits to its high half by",
         "# four byte tables; zip undoes it by four delta swaps. Masks are written",
         "# first in each AND so that the proofs reduce.",
         "import Base",
         "import ./types.bend as T", ""]
    for k, m in STAGES:
        o.append(f"def swap{k}(+x: U32) -> U32:")
        o.append(f"  +t = U32.and({m},U32.xor(x,U32.shrn(x,{k}n)))")
        o.append(f"  U32.xor(U32.xor(x,t),U32.shln(t,{k}n))")
        o.append("")
    for k in range(4):
        o.append(f"# unz of byte {k} of a word: its even bits at 4*{k}.., its odd bits at 16+4*{k}..")
        o.append(f"def ub{k}(n: Nat) -> U32:")
        o.append("  match n:")
        for b in range(256):
            o.append(f"    case {b}n: {ub_entry(b, k)}")
        o.append("    case _: 0")
        o.append("")
    o += ["# The even bits of x in its low half, the odd bits in its high half.",
          "def unz(+x: U32) -> U32:",
          "  U32.or(U32.or(ub0(U32.to_nat(U32.and(255,x))),ub1(U32.to_nat(U32.and(255,U32.shrn(x,8n))))),U32.or(ub2(U32.to_nat(U32.and(255,U32.shrn(x,16n)))),ub3(U32.to_nat(U32.shrn(x,24n)))))", "",
          "# unz's inverse.",
          "def zip(+x: U32) -> U32:",
          "  swap1(swap2(swap4(swap8(x))))", "",
          "# The even and the odd bits of a lane, from the unz of its low and high words.",
          "def even(+ul: U32, +uh: U32) -> U32:",
          "  U32.or(U32.and(65535,ul),U32.shln(uh,16n))", "",
          "def odd(+ul: U32, +uh: U32) -> U32:",
          "  U32.or(U32.shrn(ul,16n),U32.and(4294901760,uh))", "",
          "# The low and the high word of the lane with even bits e, odd bits o.",
          "def low(+e: U32, +o: U32) -> U32:",
          "  zip(U32.or(U32.and(65535,e),U32.shln(o,16n)))", "",
          "def high(+e: U32, +o: U32) -> U32:",
          "  zip(U32.or(U32.shrn(e,16n),U32.and(4294901760,o)))", ""]
    # enter / leave: whole states
    o.append("# A plain state in the interleaved representation.")
    o.append("def enter(s: T.State) -> T.St:")
    o.append("  match s:")
    o.append("    case T.S{" + ",".join(f"T.W{{+x{k},+y{k}}}" for k in range(25)) + "}:")
    fs = []
    for k in range(25):
        e, od = f"even(unz(x{k}),unz(y{k}))", f"odd(unz(x{k}),unz(y{k}))"
        if k in COMPLEMENTED:
            e, od = f"U32.not({e})", f"U32.not({od})"
        fs += [e, od]
    o.append("      T.St{" + ",".join(fs) + "}")
    o.append("")
    o.append("# enter's inverse.")
    o.append("def leave(s: T.St) -> T.State:")
    o.append("  match s:")
    o.append("    case T.St{" + plus_fields() + "}:")
    lanes = []
    for k in range(25):
        e, od = (f"U32.not(e{k})", f"U32.not(o{k})") if k in COMPLEMENTED else (f"e{k}", f"o{k}")
        lanes.append(f"T.W{{low({e},{od}),high({e},{od})}}")
    o.append("      T.S{" + ",".join(lanes) + "}")
    o.append("")
    ws = ",".join(f"w{i}: U32" for i in range(34))
    o.append("# A block's 34 words XORed into the first 17 lanes.")
    o.append(f"def mix(s: T.St,{ws}) -> T.St:")
    o.append("  match s:")
    o.append("    case T.St{" + plus_fields() + "}:")
    for j in range(17):
        o.append(f"      +l{j} = unz(w{2 * j})")
        o.append(f"      +h{j} = unz(w{2 * j + 1})")
    fs = []
    for k in range(25):
        if k < 17:
            fs.append(f"U32.xor(e{k},even(l{k},h{k}))")
            fs.append(f"U32.xor(o{k},odd(l{k},h{k}))")
        else:
            fs += [f"e{k}", f"o{k}"]
    o.append("      T.St{" + ",".join(fs) + "}")
    o.append("")
    o.append("# The first four lanes as plain lanes, the rest zero: all the digest reads.")
    o.append("def squeeze(s: T.St) -> T.State:")
    o.append("  match s:")
    o.append("    case T.St{" + plus_fields() + "}:")
    lanes = []
    for k in range(4):
        e, od = (f"U32.not(e{k})", f"U32.not(o{k})") if k in COMPLEMENTED else (f"e{k}", f"o{k}")
        lanes.append(f"T.W{{low({e},{od}),high({e},{od})}}")
    lanes += ["T.W{0,0}"] * 21
    o.append("      T.S{" + ",".join(lanes) + "}")
    o.append("")
    return "\n".join(o)


