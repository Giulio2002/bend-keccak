def gen_spec():
    o = [HEADER, "#",
         "# The interleaved representation of a state (src/types.bend St): lane k is",
         "# held as its even bits and its odd bits, each packed into a U32 (bit j of",
         "# the lane is bit j/2 of the even or the odd word), complemented for the",
         "# lanes 1, 2, 8, 12, 17, 20. Pure bit shuffles over Base's Word.",
         "import Base",
         "import ../src/types.bend as T", ""]
    lo, hi = lwords("b")
    o.append("def even(x: T.Lane) -> U32:")
