def gen_perm():
    o = [HEADER, "#",
         "# Keccak-f[1600] on bit-interleaved, partly complemented lanes. Lane k =",
         "# x + 5y is held as (e{k}, o{k}), its even and its odd bits, so every",
         "# 64-bit rotation is two 32-bit rotations; lanes 1, 2, 8, 12, 17, 20 are",
         "# held complemented, which removes most NOTs from chi. `steps` fuses two",
         "# rounds per step; `rounds` is the same permutation on plain lanes.",
         "import Base",
         "import ./types.bend as T",
         "import ./lane.bend as L", "",
         "# The zero state, with the complemented lanes all ones.",
         "def initial() -> T.St:",
         "  T.St{" + ",".join(("4294967295" if k in COMPLEMENTED else "0") for k in range(25) for _ in "eo") + "}", ""]
    for s, idx in (("e", 0), ("o", 1)):
        o.append(f"# Round constants, interleaved: their {'even' if s == 'e' else 'odd'} bits.")
        o.append(f"def rc{s}(i: Nat) -> U32:")
        o.append("  match i:")
        for i, c in enumerate(RC):
            o.append(f"    case {i}n: {split(c)[idx]}")
        o.append("    case _: 0")
        o.append("")
    ins = [(f"e{k}", f"o{k}") for k in range(25)]
    o.append("def round(s: T.St, +rce: U32, +rco: U32) -> T.St:")
    o.append("  match s:")
    o.append("    case T.St{" + plus_fields() + "}:")
    L, outs = round_body(ins, "rce", "rco", "")
    o += L
    o.append("      T.St{" + ",".join(f"{e},{od}" for e, od in outs) + "}")
    o.append("")
    o.append("def rounds_short(n: Nat, +i: Nat, s: T.St) -> T.St:")
    o.append("  match n:")
    o.append("    case 0n: s")
    o.append("    case 1n+p: rounds_short(p,1n+i,round(s,rce(i),rco(i)))")
    o.append("")
    o.append("# n rounds from round i, two fused per step.")
    o.append("def steps(n: Nat, +i: Nat, s: T.St) -> T.St:")
    o.append("  match n s:")
    o.append("    case 0n s: s")
    o.append("    case 1n s: rounds_short(1n,i,s)")
    o.append("    case 2n+p T.St{" + plus_fields() + "}:")
    o.append("      +r0e = rce(i)")
    o.append("      +r0o = rco(i)")
    L, mid = round_body(ins, "r0e", "r0o", "r0")
    o += L
    o.append("      +r1e = rce(1n+i)")
    o.append("      +r1o = rco(1n+i)")
    L, outs = round_body(mid, "r1e", "r1o", "r1")
    o += L
    o.append("      steps(p,2n+i,T.St{" + ",".join(f"{e},{od}" for e, od in outs) + "})")
    o.append("")
    o += ["# n rounds from round i on a plain state.",
          "def rounds(n: Nat, +i: Nat, s: T.State) -> T.State:",
          "  L.leave(steps(n,i,L.enter(s)))", "",
          "def permute(s: T.State) -> T.State:",
          "  rounds(24n,0n,s)", ""]
    return "\n".join(o)


