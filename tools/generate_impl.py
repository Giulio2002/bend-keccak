#!/usr/bin/env python3
"""Generate the Keccak-256 implementation and its refinement proofs.

The state keeps each 64-bit lane as its even and its odd bits in two U32s (bit
interleaving, as in XKCP's 32-bit implementations), so that each lane rotation
is two 32-bit rotations, and keeps six lanes complemented (lane complementing),
which removes most NOTs from chi.

Outputs (paths relative to the repository root):
  src/types.bend            is written by hand; src/*.bend below import it
  src/permutation.bend      round constants, rounds, the fused permutation
  src/lane.bend             word <-> interleaved lane conversion, absorb, squeeze
  src/keccak.bend           the sponge over packed little-endian words
  spec/interleave.bend      the representation relation (bit shuffles)
  proofs/permutation.bend   the permutation and the conversions against spec/
  proofs/sponge.bend        the public API against spec/sponge.bend

Every per-bit fact is discharged by a generated Bool lemma proven by case analysis;
the symbolic evaluator below mirrors Base's reduction rules (Bool.and/or/xor/not
reduce on a constructor in their first argument only) to state those lemmas.
"""
