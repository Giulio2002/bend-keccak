def ccol(x):
    return f"X{{V{{{x}n}},X{{V{{{x + 5}n}},X{{V{{{x + 10}n}},X{{V{{{x + 15}n}},V{{{x + 20}n}}}}}}}}}}"


def eb(dest):
    src, r = B[dest]
    x = src % 5
    d = f"X{{{ccol((x - 1) % 5)},R{{1n,{ccol((x + 1) % 5)}}}}}"
    return f"R{{{r}n,X{{V{{{src}n}},{d}}}}}"


def mask_b(dest):
    src, _ = B[dest]
    x = src % 5
    col = lambda c: sum((c + 5 * y) in COMPLEMENTED for y in range(5)) % 2
    d = col((x - 1) % 5) ^ col((x + 1) % 5)
    return bool((src in COMPLEMENTED) ^ d)


